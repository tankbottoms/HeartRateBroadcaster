#!/usr/bin/env bash
# Writes signing.xcconfig from apple-project.json.
#
# The team identifier is the one build setting that names the Apple Developer
# account, so it lives with the other Apple identifiers in apple-project.json
# (gitignored) rather than in project.yml (committed). Xcode cannot read JSON,
# hence this: one generated xcconfig, included by build_number.xcconfig.
#
# Run it before `xcodegen generate`. make-sideload-ipa.sh already does.
set -euo pipefail

cd "$(dirname "$0")/../.."

if [[ ! -f apple-project.json ]]; then
  echo "apple-project.json missing — copy apple-project.example.json and fill it in" >&2
  exit 1
fi

# plutil parses JSON and ships with macOS, which keeps this free of jq and of
# anything that has to be installed before the project will build.
TEAM="$(/usr/bin/plutil -extract team.id raw -o - apple-project.json)"

cat > signing.xcconfig <<CONF
// Generated by scripts/gen-xcconfig.sh — do not edit, do not commit.
DEVELOPMENT_TEAM = ${TEAM}
CONF

echo "signing.xcconfig -> DEVELOPMENT_TEAM = ${TEAM}"
